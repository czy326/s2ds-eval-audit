# -*- coding: utf-8 -*-
"""
Generate repo docs: PROVENANCE.md (table/figure -> json -> script),
.gitignore, LICENSE, CITATION.cff, and a results index.
Every mapping is derived by inspecting which script writes which file
(grep for the literal filename) so the map cannot drift from the code.
"""
import os, re, glob, json, io, sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
REPO = os.environ.get("S2DS_REPO",
                      os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CODE = os.path.join(REPO, "code")
RES = os.path.join(REPO, "results")

# ---- which script writes which output file?
res_files = sorted(os.path.basename(p) for p in glob.glob(os.path.join(RES, "*.json")))
writer_of = {}
reader_of = {}
for f in sorted(glob.glob(os.path.join(CODE, "*.py"))):
    name = os.path.basename(f)
    t = open(f, encoding="utf-8", errors="replace").read()
    for rf in res_files:
        if rf in t:
            writer_of.setdefault(rf, []).append(name)
            reader_of.setdefault(name, []).append(rf)

# ---- figure -> script
fig_scripts = {}
for f in sorted(glob.glob(os.path.join(CODE, "*.py"))):
    t = open(f, encoding="utf-8", errors="replace").read()
    if "savefig" in t or "fig1" in t or "fig2" in t:
        fig_scripts[os.path.basename(f)] = True
fig_writer = [k for k in fig_scripts if "figure" in k or "make_paper" in k]

# Manuscript table -> result file (this mapping is authored from the paper's own
# "Figures and Tables" table; kept explicit so it is auditable).
TABLE_MAP = [
    ("Table 1", "SpectralSR-Bench per-pair delta against std (8 of 10 below std)", "audit_H_spectralsr_std.json"),
    ("Table 2", "Rank correlation against mean PSNR, 8 conventions x 4 datasets", "audit_B_protocols.json"),
    ("Table 3", "Effect size against seed noise, 327 pairs", "audit_D_effect_vs_noise.json"),
    ("Table 4", "Seed noise by dataset", "audit_C_seednoise.json"),
    ("Table 5", "Report-practice statistics, 35 papers", "audit_F_field_survey.json"),
    ("Table 6", "Claimed gains against the noise floor, 7 papers", "audit_G_gain_vs_noise.json"),
    ("Table 7", "The R1 to R7 scorecard", "(authored, no data file)"),
    ("Figure 1", "Seed noise versus test-set size", "figures/fig1_noise_vs_testsize.*"),
    ("Figure 2", "Method effect versus seed noise, 327 pairs", "figures/fig2_effect_vs_noise.*"),
]

# ---- which script produces each result file's *content* (driver order)
DRIVER = {
    "audit_A_pathset.json": "s1_audit_core.py",
    "audit_B_protocols.json": "s1_audit_core.py",
    "audit_C_seednoise.json": "s1_audit_core.py",
    "audit_D_effect_vs_noise.json": "s1_effect_vs_noise.py",
    "audit_E_anchor_b3.json": "s1_anchor_b3.py",
    "audit_F_field_survey.json": "s1_field_survey.py",
    "audit_G_gain_vs_noise.json": "s1_gain_vs_noise.py",
    "audit_H_spectralsr_std.json": "s1_spectralsr_std_evidence.py",
    "audit_I_oa_resolution.json": "s1_oa_resolution.py",
    "manifest.json": "s1_build_manifest.py",
    "manifest_summary.csv": "s1_build_manifest.py",
    "_doi_meta.json": "s1_fetch_doi_meta.py + s1_patch_doi_meta.py",
    "_arxiv_meta.json": "s1_fetch_fulltext.py (arXiv API)",
}

L = []
L.append("# Provenance")
L.append("")
L.append("Every number in the manuscript traces to one result file, and every result")
L.append("file traces to one script. This page is the map. It is generated by")
L.append("`docs/_gen_provenance.py` from the actual filenames that appear inside each script,")
L.append("so the map cannot silently drift from the code.")
L.append("")
L.append("## Manuscript item to result file")
L.append("")
L.append("| Item | Content | Result file | Written by |")
L.append("|---|---|---|---|")
for item, desc, rf in TABLE_MAP:
    base = os.path.basename(rf)
    w = DRIVER.get(base, "-")
    if base not in [os.path.basename(x) for x in res_files] and not rf.startswith("figures"):
        w = "(authored)"
    if rf.startswith("figures"):
        w = " + ".join(fig_writer) or "s1_make_paper_figures.py"
    L.append(f"| {item} | {desc} | `{rf}` | `{w}` |")
L.append("")
L.append("## Result file to scripts that touch it")
L.append("")
L.append("| Result file | Scripts referencing it |")
L.append("|---|---|")
for rf in res_files:
    L.append(f"| `{rf}` | {', '.join(sorted(set(writer_of.get(rf, ['-']))))} |")
L.append("")
L.append("## Execution order")
L.append("")
L.append("The chain runner enforces dependency order, so re-running an upstream step")
L.append("cannot silently wipe a downstream upgrade.")
L.append("")
L.append("```")
L.append("s1_build_manifest.py        -> data/manifest.json")
L.append("s1_audit_core.py            -> results/audit_A, B, C")
L.append("s1_effect_vs_noise.py       -> results/audit_D")
L.append("s1_anchor_b3.py             -> results/audit_E")
L.append("s1_field_survey.py          -> results/audit_F      (resets R2/R3/R5 to tier C)")
L.append("s1_fulltext_coding.py       -> results/audit_F      (upgrades tiers from full text)")
L.append("s1_gain_vs_noise.py         -> results/audit_G      (read-only)")
L.append("s1_spectralsr_std_evidence.py -> results/audit_H")
L.append("s1_oa_resolution.py         -> results/audit_I")
L.append("s1_make_paper_figures.py    -> figures/fig1, fig2")
L.append("```")
L.append("")
L.append("`s1_fulltext_coding.py` must run after `s1_field_survey.py`. Running them in the")
L.append("other order discards the tier upgrades. `run_audit_chain.py` encodes this.")
L.append("")
L.append("## The pairing rule")
L.append("")
L.append("Only runs whose names carry an explicit seed suffix (`_s2026`, `_s2027`, `_s2028`)")
L.append("participate in method pairing. This is enforced in `s1_effect_vs_noise.py` and is")
L.append("the reason `audit_E_anchor_b3.json` exists: the anchor proves the pipeline before")
L.append("any negative finding is reported.")
L.append("")
L.append("## Survey evidence tiers")
L.append("")
L.append("`results/audit_F_field_survey.json` codes each paper on R2 (aggregation), R3 (seed")
L.append("count), and R5 (test-set composition). Each coded field carries a tier A, B, or C.")
L.append("Only tiers A and B count toward any omission rate. Tier C means the field could not")
L.append("be confirmed without the full text, and is never read as \"not reported\".")
L.append("")
L.append("The self-calibration this produces is the survey's central methodological")
L.append("constraint: the abstract-level count for seed disclosure is 0 of 35, and the")
L.append("full-text count is 4 of 35. Any count of \"papers that do not report X\" is bounded")
L.append("above by the number of full texts retrieved.")

open(os.path.join(REPO, "docs", "PROVENANCE.md"), "w", encoding="utf-8").write("\n".join(L))

