# ---- results index
idx = []
for p in sorted(glob.glob(os.path.join(RES, "*.json"))):
    try:
        d = json.load(open(p, encoding="utf-8"))
        keys = list(d.keys())[:8] if isinstance(d, dict) else f"list[{len(d)}]"
    except Exception as e:
        keys = f"<unreadable: {e}>"
    idx.append({"file": os.path.basename(p), "bytes": os.path.getsize(p), "top_keys": keys})
json.dump({"results": idx}, open(os.path.join(RES, "INDEX.json"), "w", encoding="utf-8"),
          ensure_ascii=False, indent=1)

print("docs written. results indexed:", len(idx))
for r in idx:
    print("  ", r["file"], r["bytes"], "B")
