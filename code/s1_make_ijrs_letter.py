# -*- coding: utf-8 -*-
"""
Typeset the IJRS cover letter from its Markdown source.

The letter is a standalone document, so this keeps the Markdown as the single
editable copy and derives the PDF from it rather than maintaining two texts.
"\\" at a line end is passed through as a hard line break, which is used in the
address and signature blocks.
"""
import os
import re
import io
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.environ.get("S2DS_AUDIT_ROOT") or os.path.dirname(_HERE)
_CANDS = [os.environ.get("S2DS_OUT"), os.path.join(_ROOT, "papers"),
          os.path.join(os.path.dirname(_ROOT), "out")]
OUT = next((c for c in _CANDS
            if c and os.path.exists(os.path.join(c, "P0S1_IJRS_CoverLetter.md"))),
           _CANDS[-1])

SRC = os.path.join(OUT, "P0S1_IJRS_CoverLetter.md")
DST = os.path.join(OUT, "P0S1_IJRS_CoverLetter.tex")

SKELETON = r"""\documentclass[11pt]{article}
%% Cover letter for the International Journal of Remote Sensing submission.
%% Generated by code/s1_make_ijrs_letter.py from P0S1_IJRS_CoverLetter.md.
\usepackage[a4paper,margin=2.4cm]{geometry}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\pagestyle{empty}
\setlength{\parindent}{0pt}
\setlength{\parskip}{0.5em}
\begin{document}
%(body)s
\end{document}
"""


def esc(s):
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
                 ("#", r"\#"), ("_", r"\_"), ("$", r"\$")):
        s = s.replace(a, b)
    # the hard line break marker was escaped above, so restore it
    return s.replace(r"\textbackslash{}\textbackslash{}", r"\\")


def main():
    text = open(SRC, encoding="utf-8").read()
    text = re.sub(r"(?m)^# .*\n", "", text, count=1)      # drop the title line
    blocks = [b.strip() for b in re.split(r"\n\s*\n", text) if b.strip()]

    out = []
    for b in blocks:
        lines = [esc(l) for l in b.split("\n")]
        out.append("\n".join(lines))

    doc = SKELETON % {"body": "\n\n".join(out)}
    with open(DST, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(doc)

    n_words = len(re.findall(r"[A-Za-z][A-Za-z'\-]*", text))
    print("wrote %s" % DST)
    print("blocks %d | words %d | hard breaks %d"
          % (len(blocks), n_words, text.count("\\\\")))
    for k in ("pre-submission enquiry", "editorial board", "no competing",
              "not under consideration"):
        print(("  ok   " if k in text else "  MISS ") + k)


if __name__ == "__main__":
    main()
